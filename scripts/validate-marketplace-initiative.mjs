import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
let passed=0, failed=0;
const read=(f)=>fs.readFileSync(path.join(root,f),'utf8');
const check=(name, ok)=>{ if(ok){passed++;console.log(`PASS: ${name}`)}else{failed++;console.error(`FAIL: ${name}`)} };
const ctx=read('src/context/MarketplaceContext.tsx');
const core=read('src/services/marketplaceCore.ts');
const vehicle=read('src/services/vehicleApi.ts');
const bids=read('src/services/bidApi.ts');
check('central marketplace read service exists', fs.existsSync(path.join(root,'src/services/marketplaceCore.ts')));
check('marketplace vehicle reads use canonical GET /api/cars', vehicle.includes("/api/cars"));
check('marketplace mapper is the canonical vehicle mapper', core.includes('mapBackendCarToVehicle'));
check('live auctions use canonical auction API', core.includes('auctionAPI.active'));
check('my bids use canonical backend API', core.includes('bidsAPI.myBids'));
check('authenticated bid history is loaded from server', ctx.includes('bidsAPI.myBids()'));
check('logout clears prior user bid read model', ctx.includes('if (!auth?.user?.id)') && ctx.includes('setBids([])'));
check('bid placement does not synthesize a bid ID', !ctx.includes('id: `bid_${Date.now()}`'));
check('bid placement does not locally increment current bid', !ctx.includes('bidsCount: (v.bidsCount || 0) + 1'));
check('bid API remains server-authoritative', bids.includes('POST /api/bids/:id/bid') || bids.includes('/api/bids/'));
check('core service contains no mock/demo data source', !/mockVehicles|MOCK_|demo data/i.test(core));
check('initiative does not introduce a second auction data store', !core.includes('useState'));
console.log(`\nMarketplace Core Initiative validation: ${passed}/${passed+failed} checks passed.`);
if(failed) process.exit(1);
